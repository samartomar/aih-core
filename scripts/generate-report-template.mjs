// Embeds the authored report shell (src/harness/report/templates/report.html) into src/harness/report/template.mjs.
// Usage: node scripts/generate-report-template.mjs          write src/harness/report/template.mjs
//        node scripts/generate-report-template.mjs --check  fail unless src/harness/report/template.mjs matches the authored HTML
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../src/harness/report/templates/report.html', import.meta.url);
const target = new URL('../src/harness/report/template.mjs', import.meta.url);

// Line endings are normalized so checkouts with CRLF conversion generate identical bytes.
const html = (await readFile(source, 'utf8')).replace(/\r\n/g, '\n');
const sha256 = createHash('sha256').update(html).digest('hex');
const module = `// Generated by scripts/generate-report-template.mjs from src/harness/report/templates/report.html. Do not edit.
export const TEMPLATE_SOURCE_SHA256 = '${sha256}';
export const TEMPLATE = ${JSON.stringify(html)};
`;

if (process.argv.includes('--check')) {
  let current = null;
  try { current = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n'); } catch { /* reported below */ }
  if (current !== module) {
    console.error('src/harness/report/template.mjs does not match src/harness/report/templates/report.html; run: node scripts/generate-report-template.mjs');
    process.exit(1);
  }
  console.log(`template reproduces from authored HTML (sha256 ${sha256})`);
} else {
  await writeFile(target, module);
  console.log(`wrote src/harness/report/template.mjs (sha256 ${sha256})`);
}
